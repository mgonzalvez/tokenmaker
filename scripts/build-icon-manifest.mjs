import { access, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const libraryFolder = "Fractal-Symbols-Complete-Pack";
const libraryRoot = path.join(projectRoot, libraryFolder);
const legacyFolder = "FractalSymbols Icons Set";
const legacyRoot = path.join(projectRoot, legacyFolder);
const outputPath = path.join(projectRoot, "icon-manifest.js");

// These vectors have no equivalent artwork in the newer complete pack.
// Renamed or lightly redrawn equivalents are intentionally excluded.
const legacyOnly = {
  Board: [
    "Agent circle",
    "Agent rect",
    "Agent square",
    "Disc circle",
    "Disc rect",
    "Disc square",
    "Empty rect",
    "Hex grid filled",
    "Hex grid line",
    "Hollow banner",
    "Meeple circle",
    "Meeple rect",
    "Meeple square",
    "Pawn circle",
    "Pawn rect",
    "Pawn square",
    "Simple banner",
    "Track components",
    "Track end",
    "Track middle",
    "Track single line",
  ],
  Box: ["Complexity rating", "Luck rating", "Strategy rating"],
  Combat: ["Skull"],
  Element: ["Air hex", "Arcane hex", "Death hex", "Earth hex", "Fire hex", "Life hex", "Water hex"],
  Piece: [
    "DiscCube",
    "DiscCube add",
    "DiscCube minus",
    "DiscCube move",
    "DiscCube place",
    "DiscCube remove",
    "DiscCube return",
  ],
  Resource: ["Clay", "Coal"],
};

const nameOverrides = new Map([
  ["CardInfront", "Card In Front"],
  ["Double3DDarkDice", "Double 3D Dark Dice"],
]);

function displayName(filename) {
  const stem = filename.replace(/\.svg$/i, "");
  if (nameOverrides.has(stem)) return nameOverrides.get(stem);
  return stem
    .replace(/[-_]+/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
    .replace(/([A-Za-z])(\d)/g, "$1 $2")
    .replace(/(\d)([A-Za-z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/^./, (letter) => letter.toUpperCase());
}

const categories = (await readdir(libraryRoot, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

const icons = [];

async function addIcon({ category, filename, folder, root }) {
  const name = displayName(filename);
  const id = `${category}-${name}`
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  const pngFilename = filename.replace(/\.svg$/i, ".png");

  icons.push({
    id,
    name,
    category,
    path: `${folder}/${category}/SVG/${filename}`,
    thumbnail: await access(path.join(root, category, "PNG", pngFilename))
      .then(() => `${folder}/${category}/PNG/${pngFilename}`)
      .catch(() => `${folder}/${category}/SVG/${filename}`),
    attribution: "fractal-symbols",
  });
}

for (const category of categories) {
  const svgDir = path.join(libraryRoot, category, "SVG");
  let files = [];
  try {
    files = await readdir(svgDir);
  } catch {
    continue;
  }

  for (const filename of files.filter((name) => name.toLowerCase().endsWith(".svg")).sort()) {
    await addIcon({ category, filename, folder: libraryFolder, root: libraryRoot });
  }
}

for (const [category, names] of Object.entries(legacyOnly)) {
  for (const name of names) {
    await addIcon({
      category,
      filename: `${name}.svg`,
      folder: legacyFolder,
      root: legacyRoot,
    });
  }
}

icons.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));

const banner = [
  "// Generated by scripts/build-icon-manifest.mjs.",
  "// Do not edit by hand.",
  `window.TOKENMAKER_ICONS = ${JSON.stringify(icons, null, 2)};`,
  "",
].join("\n");

await writeFile(outputPath, banner, "utf8");
console.log(`Wrote ${icons.length} icons to ${path.relative(projectRoot, outputPath)}`);
